def _spans(store: Store, exts: set[str]) -> dict[str, list[list]]:
    """Per-file `(node id, start line, end line)` span tables for the kit's
    spans.json — the research/26 insight: stitchgraph generated this kit, and
    its index already knows every function's span, so the sandbox-side
    converter needs no language parser and emits node-id-EXACT function ids."""
    out: dict[str, list[list]] = {}
    for node in store.all_nodes_full():
        if node.kind not in (NodeKind.FUNCTION, NodeKind.METHOD, NodeKind.TEST):
            continue
        rel = node.id.split("::", 1)[0]
        if os.path.splitext(rel)[1].lower() not in exts:
            continue
        parts = node.location.rsplit(":", 2)
        if len(parts) != 3 or not parts[1].isdigit():
            continue
        start = int(parts[1])
        end = node.end_line if isinstance(node.end_line, int) \
            and node.end_line >= start else start
        out.setdefault(rel, []).append([node.id, start, end])
    for entries in out.values():
        entries.sort(key=lambda e: e[1])
    return out


