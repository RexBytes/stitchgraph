# --- the universal converter (Rust / Go / JS kits): line coverage + spans.json -> canonical JSON ---
# stdlib-only python3; python3 exists in the rust:*, golang:* and node:22 (non-slim) Debian bases.
_UNI_CONVERTER = r'''#!/usr/bin/env python3
"""Convert per-test coverage captures into the canonical stitchgraph artifact (research/26).
Runs INSIDE the sandbox after the capture loop. No stitchgraph and no language parser needed:
spans.json (generated from the stitchgraph index) maps covered lines to node-id-exact functions.

Usage: to_canonical.py <format> <covdata_dir> <spans.json> <out.json> <tests.txt>
formats: llvm-json (Rust cargo-llvm-cov export) | goprofile (go -coverprofile) | istanbul (jest/vitest)
covdata holds one capture per test named <i>.<ext>; line i+1 of tests.txt is that test's id."""
import json, os, sys

fmt, covdir, spans_path, out_path, tests_path = sys.argv[1:6]
spans = json.load(open(spans_path))
ROOT = os.getcwd()

def rel_of(path):
    p = os.path.normpath(path)
    if os.path.isabs(p):
        try: p = os.path.relpath(p, ROOT)
        except ValueError: return None
    p = p.replace(os.sep, "/")
    return None if p.startswith("..") else p

_skey_cache = {}
def span_key(rel):
    """spans.json keys are relative to the stitchgraph INDEX root; when the
    capture runs in a subdirectory (a Go module / JS package inside a
    monorepo), coverage paths lack that prefix — recover via a UNIQUE
    suffix match rather than silently attributing nothing."""
    if rel in spans: return rel
    if rel not in _skey_cache:
        hits = [k for k in spans if k.endswith("/" + rel)]
        _skey_cache[rel] = hits[0] if len(hits) == 1 else None
    return _skey_cache[rel]

def innermost(rel, line):
    """Innermost enclosing span, so a nested fn isn't also credited to its parent."""
    best = None
    key = span_key(rel)
    if key is None: return None
    for nid, lo, hi in spans.get(key, ()):
        if lo <= line <= hi and (best is None or (hi - lo) < (best[2] - best[1])):
            best = (nid, lo, hi)
    return best[0] if best else None

def lines_llvm(path):
    d = json.load(open(path))
    for f in d.get("data", [{}])[0].get("functions", []):
        # an executed function's ENTRY line is inside its own span — exact for our purpose
        if f.get("count", 0) > 0 and f.get("regions") and f.get("filenames"):
            yield f["filenames"][0], f["regions"][0][0]

def lines_go(path):
    module = ""
    if os.path.exists("go.mod"):
        for ln in open("go.mod"):
            if ln.startswith("module "):
                module = ln.split()[1].strip() + "/"
                break
    for ln in open(path):
        ln = ln.strip()
        if not ln or ln.startswith("mode:"): continue
        try:
            loc, _stmts, count = ln.rsplit(" ", 2)
            if int(count) == 0: continue
            fname, rng = loc.split(":", 1)
            if module and fname.startswith(module): fname = fname[len(module):]
            lo = int(rng.split(",")[0].split(".")[0])
            hi = int(rng.split(",")[1].split(".")[0])
        except ValueError:
            continue
        for line in range(lo, hi + 1):
            yield fname, line

def lines_istanbul(path):
    d = json.load(open(path))
    for fpath, entry in d.items():
        smap, s = entry.get("statementMap", {}), entry.get("s", {})
        for sid, cnt in s.items():
            if cnt and sid in smap:
                yield fpath, smap[sid]["start"]["line"]

parse = {"llvm-json": lines_llvm, "goprofile": lines_go, "istanbul": lines_istanbul}[fmt]
test_ids = [ln.rstrip("\n") for ln in open(tests_path)]
tests = {}
for name in sorted(os.listdir(covdir)):
    stem = name.split(".", 1)[0]
    if not stem.isdigit(): continue
    idx = int(stem)
    tid = test_ids[idx] if idx < len(test_ids) else name
    try:
        hit = set()
        for fpath, line in parse(os.path.join(covdir, name)):
            rel = rel_of(fpath)
            if rel is None: continue
            nid = innermost(rel, line)
            if nid: hit.add(nid)
    except Exception as exc:                       # one bad capture never kills the batch
        print(f"skip {name}: {exc}", file=sys.stderr); continue
    if hit: tests[tid] = sorted(hit)

if not tests:
    # a 0-test artifact is the confident-absence trap: fail LOUD, write nothing
    sys.exit("ERROR: 0 tests captured — no artifact written. Common causes: the capture "
             "loop produced no files in covdata/, or coverage paths do not match "
             "spans.json (run the capture from the directory stitchgraph indexed).")
json.dump({"format": "stitchgraph-coverage-v1", "tests": tests}, open(out_path, "w"), indent=0)
print(f"wrote {out_path}: {len(tests)} tests, "
      f"{len({x for v in tests.values() for x in v})} functions")
'''

